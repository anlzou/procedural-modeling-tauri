export class MarchingCubes {
  constructor(fieldType = 'metaball', resolution = 48, centers = null, range = 1.0) {
    this.fieldType = fieldType
    this.resolution = resolution
    this.size = resolution
    this.range = range
    this.delta = (range * 2) / resolution
    this.centers = centers
    this.fieldFn = FIELD_TYPES[fieldType] || FIELD_TYPES.metaball
  }

  sample(x, y, z) {
    const val = this.fieldFn(x, y, z, this.centers)
    // 软窗口：在边界附近将场值平滑推至负值，使等值面自然终止不被切割
    const R = this.range
    const margin = R * 0.15
    const effectiveR = R - margin
    const dx = Math.max(0, Math.abs(x) - effectiveR) / margin
    const dy = Math.max(0, Math.abs(y) - effectiveR) / margin
    const dz = Math.max(0, Math.abs(z) - effectiveR) / margin
    const d = Math.max(dx, dy, dz)
    if (d <= 0) return val
    if (d >= 1) return -10
    const fade = Math.cos(d * Math.PI / 2)
    return val * fade - 0.5 * (1 - fade)
  }

  generate() {
    const positions = []
    const normals = []

    const res = this.resolution
    const delta = this.delta

    for (let x = 0; x < res; x++) {
      for (let y = 0; y < res; y++) {
        for (let z = 0; z < res; z++) {
          const R = this.range
          const p = [
            [x * delta - R, y * delta - R, z * delta - R],
            [(x + 1) * delta - R, y * delta - R, z * delta - R],
            [(x + 1) * delta - R, (y + 1) * delta - R, z * delta - R],
            [x * delta - R, (y + 1) * delta - R, z * delta - R],
            [x * delta - R, y * delta - R, (z + 1) * delta - R],
            [(x + 1) * delta - R, y * delta - R, (z + 1) * delta - R],
            [(x + 1) * delta - R, (y + 1) * delta - R, (z + 1) * delta - R],
            [x * delta - R, (y + 1) * delta - R, (z + 1) * delta - R],
          ]

          const values = p.map(pt => this.sample(pt[0], pt[1], pt[2]))

          let cubeIndex = 0
          if (values[0] < 0) cubeIndex |= 1
          if (values[1] < 0) cubeIndex |= 2
          if (values[2] < 0) cubeIndex |= 4
          if (values[3] < 0) cubeIndex |= 8
          if (values[4] < 0) cubeIndex |= 16
          if (values[5] < 0) cubeIndex |= 32
          if (values[6] < 0) cubeIndex |= 64
          if (values[7] < 0) cubeIndex |= 128

          if (edgeTable[cubeIndex] === 0) continue

          // Edge vertices
          const edgeVertices = []
          const edges = [
            [0, 1], [1, 2], [2, 3], [3, 0],
            [4, 5], [5, 6], [6, 7], [7, 4],
            [0, 4], [1, 5], [2, 6], [3, 7],
          ]

          for (let edgeIdx = 0; edgeIdx < edges.length; edgeIdx++) {
            const [i, j] = edges[edgeIdx]
            if (edgeTable[cubeIndex] & (1 << edgeIdx)) {
              const val1 = values[i], val2 = values[j]
              const t = val1 / (val1 - val2)
              const x1 = p[i][0] + t * (p[j][0] - p[i][0])
              const y1 = p[i][1] + t * (p[j][1] - p[i][1])
              const z1 = p[i][2] + t * (p[j][2] - p[i][2])
              edgeVertices.push([x1, y1, z1])
            } else {
              edgeVertices.push(null)
            }
          }

          // Generate triangles
          let i = 0
          const tri = []
          while (true) {
            const idx = cubeIndex * 16 + i
            const v = triTable[idx]
            if (v === -1) break
            tri.push(v)
            i++
          }

          for (let k = 0; k < tri.length; k += 3) {
            const v0 = edgeVertices[tri[k]]
            const v1 = edgeVertices[tri[k + 1]]
            const v2 = edgeVertices[tri[k + 2]]
            if (!v0 || !v1 || !v2) continue

            // Calculate normal
            const ax = v1[0] - v0[0], ay = v1[1] - v0[1], az = v1[2] - v0[2]
            const bx = v2[0] - v0[0], by = v2[1] - v0[1], bz = v2[2] - v0[2]
            const nx = ay * bz - az * by
            const ny = az * bx - ax * bz
            const nz = ax * by - ay * bx

            for (const v of [v0, v1, v2]) {
              positions.push(v[0], v[1], v[2])
              normals.push(nx, ny, nz)
            }
          }
        }
      }
    }

    const geometry = new THREE.BufferGeometry()
    geometry.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3))
    geometry.setAttribute('normal', new THREE.Float32BufferAttribute(normals, 3))
    return geometry
  }
}
